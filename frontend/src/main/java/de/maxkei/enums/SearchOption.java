package de.maxkei.enums;

/**
 * Enumeration representing different search options.
 */
public enum SearchOption
{
    /**
     * Represents searching for the current selection.
     */
    CURRENT,

    /**
     * Represents searching for the previous occurrence.
     */
    PREVIOUS,

    /**
     * Represents searching for the next occurrence.
     */
    NEXT,

    /**
     * Represents exiting the search.
     */
    EXIT
}
